"""Generates the state table of the port from the statetype initializers of the C files.

WL_STATE.BI: the routine ids and state ids (constants)
WL_STATE.BM: InitStates (SetState lines, in $If blocks like the C #ifdefs) and CallStateRoutine

WL_STATE.BI keeps everything from the "hand-written tables" marker line on.
Add newly ported routines to PORTED, then run: python tools/gen_states.py
"""
import os
import re

# run from anywhere: python tools/gen_states.py (paths are relative to the repository)
W = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..') + '/'
O = W + 'origsrc/'
B = W + 'basicsrc/'  # the QB64 sources

# routines that are ported (the others dispatch to nothing yet)
PORTED = ['T_Player', 'T_Attack', 'T_Stand', 'T_Path', 'T_Chase', 'T_DogChase', 'T_Shoot', 'T_Bite',
          'A_DeathScream', 'T_Ghosts', 'T_Projectile', 'A_Smoke',
          'T_Schabb', 'T_SchabbThrow', 'T_Gift', 'T_GiftThrow', 'T_Fat', 'T_Fake', 'T_FakeFire',
          'A_MechaSound', 'A_HitlerMorph', 'A_Slurpie', 'A_StartDeathCam',
          'T_BJRun', 'T_BJJump', 'T_BJYell', 'T_BJDone',
          'T_UShoot', 'T_Will', 'T_Launch', 'A_Victory', 'A_StartAttack', 'A_Relaunch', 'A_Breathing',
          'A_Dormant']

STATE_RE = re.compile(r'^\s*statetype\s+(s_\w+)\s*=\s*\{([^}]*)\}\s*;')


def scan(fname):
    """[(state, fields, conds)] with conds the list of open #if conditions"""
    out = []
    stack = []
    for line in open(O + fname, encoding='latin-1'):
        s = line.strip()
        m = re.match(r'#\s*ifdef\s+(\w+)', s)
        if m:
            stack.append(m.group(1) + ' = DEFINED'); continue
        m = re.match(r'#\s*ifndef\s+(\w+)', s)
        if m:
            stack.append(m.group(1) + ' = UNDEFINED'); continue
        if re.match(r'#\s*if\b', s):
            stack.append('?' + s); continue
        if re.match(r'#\s*else', s):
            c = stack.pop()
            if c.endswith('= DEFINED'):
                c = c.replace('= DEFINED', '= UNDEFINED')
            elif c.endswith('= UNDEFINED'):
                c = c.replace('= UNDEFINED', '= DEFINED')
            else:
                c = '!' + c
            stack.append(c); continue
        if re.match(r'#\s*endif', s):
            stack.pop(); continue
        m = STATE_RE.match(line)
        if m:
            fields = [f.strip() for f in m.group(2).split(',')]
            assert len(fields) == 6, (m.group(1), fields)
            assert not any(c.startswith(('?', '!')) for c in stack), (m.group(1), stack)
            out.append((m.group(1), fields, list(stack)))
    return out


states = scan('WL_AGENT.C') + scan('WL_ACT2.C')

routines = []
for _, f, _c in states:
    for r in (f[3], f[4]):
        if r != 'NULL' and r not in routines:
            routines.append(r)
# keep T_Player = 1 as before
routines.remove('T_Player')
routines.insert(0, 'T_Player')

names = [s for s, _, _ in states]
assert len(names) == len(set(n.lower() for n in names))


def val_bool(v):
    return {'true': '1', 'false': '0'}.get(v, v)


def rt(v):
    return 'RT_NONE' if v == 'NULL' else 'RT_' + v.upper()


def nxt(v):
    return '0' if v == 'NULL' else v.lstrip('&')


# ---- WL_STATE.BI
bi = []
bi.append("' The state table - statetype variables of WL_AGENT.C / WL_ACT2.C")
bi.append("'")
bi.append("' C has one statetype variable per state (s_player, s_grdstand...), with the next state and")
bi.append("' the think / action routines as pointers. Here the states are rows of states(), named")
bi.append("' by constants (index 0 = NULL), and the routines are ids dispatched by CallStateRoutine.")
bi.append("' Generated from the C initializers (gen_states.py); InitStates in WL_STATE.BM fills the table.")
bi.append("$If INCLUDE_WL_STATE_BI = UNDEFINED Then")
bi.append("    $Let INCLUDE_WL_STATE_BI = 1")
bi.append("")
bi.append("    Const MAXSTATES = %d" % (len(states)))
bi.append("    Dim Shared states(0 To MAXSTATES) As statetype")
bi.append("")
bi.append("    '")
bi.append("    ' routine ids (think / action), 0 = NULL")
bi.append("    '")
bi.append("    Const RT_NONE = 0")
for i, r in enumerate(routines):
    bi.append("    Const %s = %d" % (rt(r), i + 1))
bi.append("")
bi.append("    '")
bi.append("    ' state ids, 0 = NULL (the Spear-only ones exist as ids in WL6 too)")
bi.append("    '")
for i, s in enumerate(names):
    bi.append("    Const %s = %d" % (s, i + 1))
bi.append("")
# keep the hand-written tables (from the marker line to the end)
MARKER = "    ' ---- hand-written tables"
old = open(B + 'WL_STATE.BI', encoding='utf-8', newline='').read().replace('\r\n', '\n')
if MARKER in old:
    bi.append(old[old.index(MARKER):].rstrip('\n'))
else:
    bi.append("$End If")
open(B + 'WL_STATE.BI', 'w', encoding='utf-8', newline='\r\n').write('\n'.join(bi) + '\n')

# ---- InitStates / CallStateRoutine
init = []
init.append("    ' The statetype initializers of the C files (generated by gen_states.py)")
init.append("    ' statetype s = {rotate, shapenum, tictime, think, action, next}")
init.append("    Sub InitStates ()")
open_conds = []
src = None
for s, f, conds in states:
    fsrc = 'WL_AGENT.C' if s in ('s_player', 's_attack') else 'WL_ACT2.C'
    # close / open $If blocks
    k = 0
    while k < len(open_conds) and k < len(conds) and open_conds[k] == conds[k]:
        k += 1
    while len(open_conds) > k:
        open_conds.pop()
        init.append("    " * (len(open_conds) + 2) + "$End If")
    if fsrc != src:
        init.append("    " * (len(open_conds) + 2) + "' " + fsrc)
        src = fsrc
    while len(open_conds) < len(conds):
        init.append("    " * (len(open_conds) + 2) + "$If %s Then" % conds[len(open_conds)])
        open_conds.append(conds[len(open_conds)])
    ind = "    " * (len(open_conds) + 2)
    init.append(ind + "SetState %s, %s, %s, %s, %s, %s, %s" % (s, val_bool(f[0]), f[1], f[2], rt(f[3]), rt(f[4]), nxt(f[5])))
while open_conds:
    open_conds.pop()
    init.append("    " * (len(open_conds) + 2) + "$End If")
init.append("    End Sub")
init.append("")
init.append("    ' Calls a think / action routine of a state (C function pointer) for object ob")
init.append("    Sub CallStateRoutine (routine As Integer, ob As Integer)")
init.append("        Select Case routine")
for r in routines:
    if r in PORTED:
        init.append("            Case %s" % rt(r))
        init.append("                %s ob" % r)
todo = [r for r in routines if r not in PORTED]
init.append("            Case Else")
if todo:
    init.append("                ' not ported: " + ", ".join(todo))
else:
    init.append("                ' (RT_NONE: no routine)")
init.append("        End Select")
init.append("    End Sub")

bm = open(B + 'WL_STATE.BM', encoding='utf-8').read().replace('\r\n', '\n')
i = bm.index("    ' The statetype initializers of the C files")
# the include guard's $End If at the end of the file (the QB64 IDE writes "$End If", earlier "$EndIf")
j = max(bm.rfind("\n$End If"), bm.rfind("\n$EndIf")) + 1
assert j > i, "the final $End If of WL_STATE.BM was not found"
bm = bm[:i] + '\n'.join(init) + '\n\n' + bm[j:]
open(B + 'WL_STATE.BM', 'w', encoding='utf-8', newline='\r\n').write(bm)
print(len(states), 'states,', len(routines), 'routines; todo:', len(todo))
