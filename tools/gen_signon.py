"""Generates the data that the original builds linked into the exe (SIGNON.OBJ, GAMEPAL.OBJ):

  GAMEPAL.BAS       LoadGamePalette: the palette (OBJ/gamepal.bin; Spear: OBJ/gamepal_sod.bin,
                    the same in both Spear exes, it differs in the colours 166 and 167)
  SIGNON_WL6.BAS    LoadSignonScreen: the sign-on screen, 320x200 bytes (OBJ/signon.bin, WOLF3D)
  SIGNON_WL1.BAS    the same for the v1.0 shareware, with the Apogee logo (OBJ/signon_wl1.bin;
                    its palette, OBJ/gamepal_wl1.bin, is the same as WL6's)
  SIGNON_SOD.BAS    the same for Spear of Destiny (OBJ/signon_sod.bin)
  SIGNON_SDM.BAS    the same for the Spear of Destiny demo (OBJ/signon_sdm.bin)

WOLF3D.BAS includes the files of the build, so the exe needs no files besides the game data.
The Spear and v1.0 .bin files come from the original exes, see tools/extract_exe_data.py.
The screen is written as text, two letters A-P per byte (the high and the low 4 bits).

python tools/gen_signon.py
"""
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
BYTES_PER_LINE = 128


def write(name, lines):
    path = os.path.join(ROOT, name)
    new = '\r\n'.join(lines) + '\r\n'
    old = open(path, encoding='latin-1', newline='').read() if os.path.exists(path) else None
    if old is None or old.replace('\r\n', '\n') != new.replace('\r\n', '\n'):
        open(path, 'w', encoding='latin-1', newline='').write(new)
        print('wrote', name)


def palette_lines(pal, indent):
    return [indent + 'gamepal(%d) = _RGB32(%d, %d, %d)' % (i, pal[i * 3], pal[i * 3 + 1], pal[i * 3 + 2])
            for i in range(256)]


def gamepal():
    wolf = open(os.path.join(ROOT, 'OBJ', 'gamepal.bin'), 'rb').read()
    spear = open(os.path.join(ROOT, 'OBJ', 'gamepal_sod.bin'), 'rb').read()
    lines = ["' GAMEPAL.BAS - the game palette (GAMEPAL.OBJ of the original builds)",
             "' Generated by tools/gen_signon.py from OBJ/gamepal.bin and OBJ/gamepal_sod.bin",
             "",
             "Sub LoadGamePalette",
             "    ' gamepal() is Dim Shared in ID_VL.BI, needed by VW_FadeIn",
             "    Dim i As Integer",
             "",
             "    $If SPEAR = UNDEFINED Then"]
    lines += palette_lines(wolf, '        ')
    lines += ["    $Else",
              "        ' (Spear of Destiny: the colours 166 and 167 are different)"]
    lines += palette_lines(spear, '        ')
    lines += ["    $End If",
              "",
              "    ' Set the palette, VGA DAC values are 6-bit (0-63), scale them to 8-bit",
              "    For i = 0 To 255",
              "        gamepal(i) = _RGB32(_Red32(gamepal(i)) * 255 \\ 63, _Green32(gamepal(i)) * 255 \\ 63, _Blue32(gamepal(i)) * 255 \\ 63)",
              "        _PaletteColor i, gamepal(i)",
              "    Next i",
              "End Sub"]
    write('GAMEPAL.BAS', lines)


def signon(name, src, what):
    data = open(os.path.join(ROOT, 'OBJ', src), 'rb').read()
    assert len(data) == 64000, (src, len(data))
    lines = ["' %s - the sign-on screen of %s (SIGNON.OBJ of the original build)" % (name, what),
             "' Generated by tools/gen_signon.py from OBJ/%s, do not edit" % src,
             "",
             "Sub LoadSignonScreen (introscn() As _Unsigned _Byte)",
             "    ' 320x200 bytes, two letters A-P per byte (high, low 4 bits)",
             "    Dim s As String, i As Long",
             ""]
    for k in range(0, 64000, BYTES_PER_LINE):
        chunk = data[k:k + BYTES_PER_LINE]
        text = ''.join(chr(65 + (b >> 4)) + chr(65 + (b & 15)) for b in chunk)
        lines.append('    s = s + "%s"' % text)
    lines += ["",
              "    For i = 0 To 63999",
              "        introscn(i) = (Asc(s, i * 2 + 1) - 65) * 16 + Asc(s, i * 2 + 2) - 65",
              "    Next i",
              "End Sub"]
    write(name, lines)


def main():
    wl1 = open(os.path.join(ROOT, 'OBJ', 'gamepal_wl1.bin'), 'rb').read()
    if wl1 != open(os.path.join(ROOT, 'OBJ', 'gamepal.bin'), 'rb').read():
        raise SystemExit('the v1.0 palette is no longer the WL6 one: GAMEPAL.BAS needs it too')
    gamepal()
    signon('SIGNON_WL6.BAS', 'signon.bin', 'Wolfenstein 3-D')
    signon('SIGNON_WL1.BAS', 'signon_wl1.bin', 'the Wolfenstein 3-D v1.0 shareware')
    signon('SIGNON_SOD.BAS', 'signon_sod.bin', 'Spear of Destiny')
    signon('SIGNON_SDM.BAS', 'signon_sdm.bin', 'the Spear of Destiny demo')


if __name__ == '__main__':
    main()
